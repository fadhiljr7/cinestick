"""Lay the checked voice lines end to end and write everything the scenes need.

  python tools/voice/assemble.py --project projects/<slug>

In:  <project>/input/lines.json   [{id, who, vo, voice, speed, treat, beat?, text, asr?}]
     <project>/voices/<id>.wav    one file per line (made by voices.py)
     <project>/voices/words.json  {id: [[word, t0, t1], ...]}  (asr_check.py format)
Out: input/voiceover.wav, input/script.txt, timeline/{words,lines,sentences}.json + transcript.txt, scenes/dialogue.js
"""
import argparse, json, re, sys
from pathlib import Path
import numpy as np, soundfile as sf

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))      # tools/ (common.py)
from common import write_timeline, sentences_from_words

SR = 24000
GAP_FIRST, GAP_SAME, GAP_REPLY, GAP_BEAT = 0.05, 0.14, 0.22, 0.4
BEAT_PAUSE = {'turn', 'reveal'}          # a held breath before "Then…" and "You see…"


def slugify(title: str) -> str:
    return re.sub(r'[^a-z0-9]+', '-', title.lower()).strip('-') or 'video'


def out_name(title: str) -> str:
    """The final MP4's file name, exactly as audio/mix.py names it."""
    return (re.sub(r'[^\w\- ]+', '', title or 'video').strip().replace(' ', '_') or 'video') + '.mp4'


def gap_before(prev, cur) -> float:
    if prev is None: return GAP_FIRST
    if cur.get('beat') in BEAT_PAUSE: return GAP_BEAT
    return GAP_SAME if prev.get('who') == cur.get('who') else GAP_REPLY


def line_words(line: dict, asr: list, t0: float, dur: float) -> list:
    """Words of one line in global time. The script's spelling is shown only when it has as many tokens as Whisper heard;
    otherwise Whisper's own words are kept so caption text never drifts from its timing."""
    toks = line['text'].split()
    mk = lambda w, a, b: {'word': w, 'start': round(t0 + max(0.0, a), 3), 'end': round(t0 + min(b, dur), 3), 'line': line.get('id')}
    if len(toks) == len(asr):
        return [mk(toks[i], a, b) for i, (_, a, b) in enumerate(asr)]
    # Different counts: align, and always show the script's spelling. A run of script tokens that Whisper heard differently
    # ("thousand-piece" / "thousand" "-piece", "sixty" / "60", "one hundred sixty" / "160") shares Whisper's time span evenly;
    # script words Whisper skipped get a short slot at the previous word's end; words Whisper added are dropped.
    import difflib
    norm = lambda s: re.sub(r"[^\w']", '', s.lower())
    out = []
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, [norm(t) for t in toks], [norm(w) for w, _, _ in asr], autojunk=False).get_opcodes():
        if op == 'equal': out += [mk(toks[i1 + k], asr[j1 + k][1], asr[j1 + k][2]) for k in range(i2 - i1)]
        elif op == 'replace':
            a, b, n = asr[j1][1], asr[j2 - 1][2], i2 - i1
            out += [mk(toks[i1 + k], a + (b - a) * k / n, a + (b - a) * (k + 1) / n) for k in range(n)]
        elif op == 'delete':
            t = (out[-1]['end'] - t0) if out else (asr[0][1] if asr else 0.0)
            out += [mk(toks[i1 + k], t, t + 0.05) for k in range(i2 - i1)]
    return out


def _mono(path):
    x, sr = sf.read(str(path), dtype='float32')
    if x.ndim > 1: x = x.mean(1)
    if sr != SR:
        from scipy.signal import resample_poly
        x = resample_poly(x, SR, sr).astype(np.float32)
    return x


def assemble(project_dir, lines, voices_dir) -> dict:
    P, V = Path(project_dir), Path(voices_dir)
    W = json.load(open(V / 'words.json'))
    t, prev, clips, out_lines, words = 0.0, None, [], [], []
    for l in lines:
        t += gap_before(prev, l)
        x = _mono(V / f"{l['id']}.wav"); dur = len(x) / SR
        out_lines.append({'id': l['id'], 'who': l.get('who', 'narrator'), 'vo': bool(l.get('vo', True)), 'beat': l.get('beat'),
                          't0': round(t, 3), 't1': round(t + dur, 3), 'text': l['text']})
        words += line_words(l, W.get(l['id'], []), t, dur)
        clips.append((t, x)); t += dur; prev = l
    y = np.zeros(int((t + 0.3) * SR), np.float32)
    for t0, x in clips: i = int(round(t0 * SR)); y[i:i + len(x)] += x
    peak = float(np.abs(y).max()) or 1.0
    y *= 0.9 / peak
    for d in ['input', 'timeline', 'scenes']: (P / d).mkdir(parents=True, exist_ok=True)
    sf.write(str(P / 'input/voiceover.wav'), y, SR)
    (P / 'input/script.txt').write_text('\n'.join(l['text'] for l in lines) + '\n')
    write_timeline(str(P / 'timeline'), words, sentences_from_words(words), 'kokoro per line + faster-whisper check')
    json.dump(out_lines, open(P / 'timeline/lines.json', 'w'), indent=1)
    (P / 'scenes/dialogue.js').write_text('// generated by tools/voice/assemble.py: who speaks when (global seconds)\nexport const LINES = '
                                          + json.dumps({l['id']: l for l in out_lines}) + ';\n')
    return {'duration': round(len(y) / SR, 3), 'lines': len(out_lines)}


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--project', required=True); a = ap.parse_args()
    P = Path(a.project); r = assemble(P, json.load(open(P / 'input/lines.json')), P / 'voices')
    print(f"voiceover {r['duration']} s, {r['lines']} lines -> {P / 'input/voiceover.wav'}")
